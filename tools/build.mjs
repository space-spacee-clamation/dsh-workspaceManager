/**
 * Build dsh-workspace-manager.
 *
 * Host half: every file under `src/` that is NOT the browser half is copied to
 * `lib/` verbatim — plain ESM, relative imports, no bundler. `src/host.js`
 * becomes `lib/index.js` (the package `main`); `src/host/*.js` keeps its
 * relative path so `./host/x.js` specifiers stay valid after the copy.
 *
 * Browser half: the DSH client module system serves `lib/client.js` as a
 * classic script that registers a closure factory:
 *
 *   window.__ModuleLoader__.load({ id: "<pkg>", factory: (require) => { … } })
 *
 * so this script wraps the (import-free) browser source into exactly that
 * registration. Nothing else may appear at the top level of the emitted file,
 * and `require` may only ask for platform modules.
 *
 * Usage: node tools/build.mjs [--check]
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8')

/**
 * Module specifiers the shell seeds into the frozen module table. Mirrors
 * `PLATFORM_MODULES` in `@deepseek-ai/dsh-client-web/src/platform.ts`; a
 * request outside this set would throw at materialization time.
 */
const PLATFORM_MODULES = new Set([
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
])

/** The single browser source file, and the factory function it must define. */
const CLIENT_SOURCE = 'src/client.js'
const CLIENT_FACTORY = 'createWorkspaceManagerPlugin'

/** Host source that becomes the package main. */
const HOST_ENTRY = 'src/host.js'

const manifest = JSON.parse(read('package.json'))

/**
 * Fail loud instead of shipping a file the module system cannot evaluate.
 * @param label - file name for the diagnostic.
 * @param source - candidate factory body.
 */
function assertNoModuleSyntax(label, source) {
  const match = /^\s*(import|export)\s/m.exec(source)
  if (match !== null) {
    throw new Error(`${label}: top-level "${match[1]}" is not allowed in the factory body`)
  }
}

/**
 * Every `require('…')` inside the browser half must name a platform module.
 * @param source - candidate factory body.
 */
function assertPlatformRequires(source) {
  const pattern = /require\(\s*['"]([^'"]+)['"]\s*\)/g
  for (const match of source.matchAll(pattern)) {
    if (!PLATFORM_MODULES.has(match[1])) {
      throw new Error(`${CLIENT_SOURCE} requires "${match[1]}", which is not a platform module`)
    }
  }
}

/**
 * Every relative ESM specifier in a host file must have a source beside it, so
 * the verbatim copy cannot ship a dangling import.
 * @param relative - host source path relative to the package root.
 * @param source - file contents.
 */
function assertRelativeImportsResolve(relative, source) {
  const pattern = /from\s+['"](\.[^'"]+)['"]/g
  for (const match of source.matchAll(pattern)) {
    const target = path.resolve(root, path.dirname(relative), match[1])
    if (!fs.existsSync(target)) {
      throw new Error(`${relative} imports "${match[1]}", which does not exist`)
    }
  }
}

/** Every host source file that ships to `lib/`, excluding the browser half. */
function hostSources(dir = 'src', found = []) {
  for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
    const relative = `${dir}/${entry.name}`
    if (entry.isDirectory()) hostSources(relative, found)
    else if (entry.name.endsWith('.js') && relative !== CLIENT_SOURCE) found.push(relative)
  }
  return found.sort()
}

const client = read(CLIENT_SOURCE)
assertNoModuleSyntax(CLIENT_SOURCE, client)
assertPlatformRequires(client)

if (!new RegExp(`^function ${CLIENT_FACTORY}\\(require\\)`, 'm').test(client)) {
  throw new Error(`${CLIENT_SOURCE} must define ${CLIENT_FACTORY}(require)`)
}

const bundle = `// Generated by tools/build.mjs — do not edit.
// Browser half of ${manifest.name}@${manifest.version}: one registration in the
// client module system's factory form, serving the Workspace Manager panel.
window.__ModuleLoader__.load({ id: ${JSON.stringify(manifest.name)}, factory: function (require) {
'use strict';
${client}
return ${CLIENT_FACTORY}(require);
} });
`

const sources = hostSources()
const hostEntry = sources.includes(HOST_ENTRY)
if (!hostEntry) throw new Error(`${HOST_ENTRY} is missing`)

for (const relative of sources) {
  assertRelativeImportsResolve(relative, read(relative))
}

const emitted = new Map()
for (const relative of sources) {
  const target = relative === HOST_ENTRY ? 'lib/index.js' : `lib/${relative.slice('src/'.length)}`
  emitted.set(target, read(relative))
}
emitted.set('lib/client.js', bundle)

if (process.argv.includes('--check')) {
  const stale = []
  for (const [target, content] of emitted) {
    const current = fs.existsSync(path.join(root, target)) ? read(target) : undefined
    if (current !== content) stale.push(target)
  }
  if (stale.length > 0) {
    console.error(`stale build output: ${stale.join(', ')}`)
    process.exit(1)
  }
  console.log(`Build output is current (${emitted.size} files).`)
} else {
  for (const [target, content] of emitted) {
    const file = path.join(root, target)
    fs.mkdirSync(path.dirname(file), { recursive: true })
    fs.writeFileSync(file, content)
  }
  console.log(`Built ${manifest.name}@${manifest.version}:`)
  for (const target of [...emitted.keys()].sort()) {
    console.log(`  ${target.padEnd(28)} ${fs.statSync(path.join(root, target)).size} bytes`)
  }
  console.log(`Browser half allows ${PLATFORM_MODULES.size} platform externals.`)
}
